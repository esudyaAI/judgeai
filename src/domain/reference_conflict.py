"""Domain Layer — конфликт справочных данных (T15.16).

Противоречие в загруженных данных — две редакции статьи с одной датой получения (T15.15),
несравнимые версии парсера (T15.14) — закрывается отказом, а не случайным выбором (DoD T23).
Это не ошибка программы: API отвечает на него явным «проверка не выполнена», анализ —
предупреждением. Подкласс ValueError — прежние вызывающие продолжают его ловить.
"""

CONFLICT_DETAIL = (
    "Конфликт справочных данных: загружены противоречащие редакции или разборы УК РФ. "
    "Проверка по ним не выполнена."
)


class ReferenceDataConflict(ValueError):
    """Загруженные справочные данные противоречат друг другу; выбирать между ними нельзя."""
